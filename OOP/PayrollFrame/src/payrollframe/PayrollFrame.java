    private void loadCsv() {
        try (BufferedReader br = new BufferedReader(new FileReader(CSV))) {
            br.readLine(); // skip header
            String line;

            while ((line = br.readLine()) != null) {
                String[] d = line.split(",",-1);

                int id = Integer.parseInt(d[0]);
                String name = d[1];
                String email = d[2];
                double salary = Double.parseDouble(d[3]);
                double allowance = Double.parseDouble(d[4]);

                Employee emp = new Employee(id, name, email, salary, allowance);

                model.addRow(new Object[]{
                    emp.getId(), emp.getName(), emp.getEmail(), emp.getSalary(), emp.getAllowance(), emp.getGrossSalary()
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "CSV Load Error:\n" + e.getMessage());
            e.printStackTrace(); 
        }
    }

    
    private void addRecord() {

        int newId = 1;

        if (model.getRowCount() > 0) {
            int lastRow = model.getRowCount() - 1;
            newId = Integer.parseInt(model.getValueAt(lastRow, 0).toString()) + 1;
        }

        String name = jTextName.getText();
        String email = jTextEmail.getText();

        double salary;
        double allowance;

        try {
            salary = Double.parseDouble(jTextSalary.getText());
            allowance = Double.parseDouble(jTextAllowance.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Salary and Allowance must be numbers");
            return;
        }
        
        Employee emp = new Employee(newId, name, email, salary, allowance);
        
        
        
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(CSV, true))) {
            bw.newLine();
            bw.write(emp.getId() + "," +
                     emp.getName() + "," +
                     emp.getEmail() + "," +
                     emp.getSalary() + "," +
                     emp.getAllowance());
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "CSV Save Error:\n" + e.getMessage());
            return;
        }

                model.addRow(new Object[]{
                    emp.getId(), emp.getName(), emp.getEmail(), emp.getSalary(), emp.getAllowance(), emp.getGrossSalary()
                });
    }

    
    private void refreshTable() {
        model.setRowCount(0); 
        loadCsv();           
    }
    
